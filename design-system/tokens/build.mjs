// Builds tokens.css and EXTENSIONS.md from tokens.mjs.
// Run from design-system/:  node tokens/build.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { themed, accents, fixed, roles, breakpoints } from './tokens.mjs';

const out = (name) => fileURLToPath(new URL(name, import.meta.url));
const note = (t) => (t.ext ? `/* EXTENSION: ${t.ext} */` : `/* site: ${t.from} */`);
const line = (name, value, t) => `  --${name}: ${value}; ${note(t)}`;

// ---- Build the declaration lists --------------------------------------------------------------
const light = [];
const dark = [];

// Every themed token is written in both theme blocks. A value that refers to another variable
// (var(--color-line)) is resolved where it is declared, so skipping the dark copy would leave a
// dark container holding the light value.
for (const [name, t] of Object.entries(themed)) {
  light.push(line(name, t.light, t));
  dark.push(line(name, t.dark, t));
}

for (const [name, a] of Object.entries(accents)) {
  const parts = { wash: 'wash', muted: 'muted', ink: 'ink', text: 'text' };
  for (const [key, label] of Object.entries(parts)) {
    // Sky has only wash and muted on the site; ink and text are extensions.
    const isExt = a.ext && (key === 'ink' || key === 'text');
    const t = isExt ? { ext: a.ext } : { from: a.from };
    light.push(line(`accent-${name}-${label}`, a[key][0], t));
    dark.push(line(`accent-${name}-${label}`, a[key][1], t));
  }
}

// With no data-accent set, the accent roles fall back to neutrals.
const neutral = {
  wash: ['var(--color-surface-2)', { ext: 'Neutral default so a screen with no accent still has valid values.' }],
  muted: ['var(--color-muted)', { ext: 'Neutral default.' }],
  ink: ['var(--color-ink)', { ext: 'Neutral default.' }],
  text: ['var(--color-ink)', { ext: 'Neutral default.' }],
};
for (const [key, [value, t]] of Object.entries(neutral)) {
  light.push(line(`accent-${key}`, value, t));
  dark.push(line(`accent-${key}`, value, t));
}

const fixedLines = [];
const mobileLines = [];
for (const [name, t] of Object.entries(fixed)) {
  if (String(t.value).includes('var(')) {
    // Refers to a theme colour, so it must be declared inside each theme block.
    light.push(line(name, t.value, t));
    dark.push(line(name, t.value, t));
    continue;
  }
  fixedLines.push(line(name, t.value, t));
  if (t.mobile) mobileLines.push(line(name, t.mobile, t));
}
for (const [name, r] of Object.entries(roles)) {
  const p = `type-${name}`;
  fixedLines.push(line(`${p}-size`, r.size, r));
  fixedLines.push(`  --${p}-weight: ${r.weight};`);
  fixedLines.push(`  --${p}-stretch: ${r.stretch};`);
  fixedLines.push(`  --${p}-lh: ${r.lh};`);
  fixedLines.push(`  --${p}-tracking: ${r.tracking};`);
  if (r.mobile && r.mobile !== r.size) mobileLines.push(line(`${p}-size`, r.mobile, r));
}

const accentSelectors = Object.keys(accents)
  .map(
    (n) =>
      `[data-accent="${n}"] {\n  --accent-wash: var(--accent-${n}-wash);\n  --accent-muted: var(--accent-${n}-muted);\n  --accent-ink: var(--accent-${n}-ink);\n  --accent-text: var(--accent-${n}-text);\n}`,
  )
  .join('\n');

const css = `/* GENERATED by tokens/build.mjs from tokens.mjs. Do not edit by hand.
 *
 * Every value has a comment beside it:
 *   site: ...       read from the live portfolio CSS
 *   EXTENSION: ...  the portfolio has no answer, so the value is proposed
 *
 * Themes: light is the default. Dark follows the system, and data-theme="light" or
 * data-theme="dark" on any element forces a theme for everything inside it.
 * Accent: put data-accent="violet" (amber, teal, coral, sky) on an element. One per screen.
 */

:root,
[data-theme="light"] {
  color-scheme: light;
${light.join('\n')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${dark.map((l) => '  ' + l).join('\n')}
  }
}

[data-theme="dark"] {
  color-scheme: dark;
${dark.join('\n')}
}

:root {
${fixedLines.join('\n')}
}

@media (max-width: ${breakpoints.mobile.max}px) {
  :root {
${mobileLines.map((l) => '  ' + l).join('\n')}
  }
}

/* Reduced motion: every duration collapses. The site honours this with its own toggle too. */
@media (prefers-reduced-motion: reduce) {
  :root {
    --dur-press: 0s; --dur-fast: 0s; --dur-base: 0s; --dur-slow: 0s; --dur-spring: 0s; --dur-colour: 0s;
  }
}

${accentSelectors}
`;

writeFileSync(out('tokens.css'), css);

// ---- EXTENSIONS.md ----------------------------------------------------------------------------
const rows = [];
for (const [name, t] of Object.entries({ ...themed, ...fixed })) if (t.ext) rows.push([name, t.ext]);
for (const [name, a] of Object.entries(accents)) if (a.ext) rows.push([`accent-${name}-ink and accent-${name}-text`, a.ext]);
rows.push(['accent-wash, accent-muted, accent-ink, accent-text', 'Neutral default so a screen with no accent still has valid values.']);
rows.push(['prefers-reduced-motion block', 'Zeroes every duration at token level. The site has a Reduce motion toggle, but no token level rule.']);

const md = `# Extensions

Every token that is not read from the live portfolio. Each one fills a gap the portfolio never needed to answer. This list feeds the "where it breaks" section of the README.

${rows.map(([n, why]) => `- \`${n}\`: ${why}`).join('\n')}
`;
writeFileSync(out('EXTENSIONS.md'), md);
console.log(`tokens.css written (${light.length} light, ${dark.length} dark, ${fixedLines.length} fixed). ${rows.length} extensions.`);
