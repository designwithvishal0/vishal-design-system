// Builds tokens.css and EXTENSIONS.md from tokens.mjs.
// Run from design-system/:  node tokens/build.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { themed, accents, neutralAccent, neutralNote, textAaNote, fixed, roles, breakpoints } from './tokens.mjs';

// ---- Check: every accent text-aa value must pass 4.5 to 1 on its wash, the page and surface-1 ----
const lum = (hex) => {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => { const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x); return (hi + 0.05) / (lo + 0.05); };
for (const [name, a] of Object.entries(accents)) {
  [0, 1].forEach((i) => {
    const text = a.textAa[i];
    const page = themed['color-bg'][i ? 'dark' : 'light'];
    const surface = themed['color-surface-1'][i ? 'dark' : 'light'];
    for (const [what, bg] of [['wash', a.wash[i]], ['page', page], ['surface-1', surface]]) {
      if (ratio(text, bg) < 4.5) throw new Error(`accent ${name} text-aa ${text} is below 4.5 to 1 on ${what} (${i ? 'dark' : 'light'})`);
    }
  });
}

const out = (name) => fileURLToPath(new URL(name, import.meta.url));
const note = (t) => (t.ext ? `/* EXTENSION: ${t.ext} */` : `/* site: ${t.from} */`);
const line = (name, value, t) => `  --${name}: ${value}; ${note(t)}`;

// ---- Build the declaration lists --------------------------------------------------------------
const light = [];
const dark = [];

// Every themed token is written in both theme blocks. A value that refers to another variable
// (var(--color-line)) is resolved where it is declared, so skipping the dark copy would leave a
// dark container holding the light value.
for (const [name, t] of Object.entries(themed)) {
  light.push(line(name, t.light, t));
  dark.push(line(name, t.dark, t));
}

const accentParts = { wash: 'wash', muted: 'muted', ink: 'ink', text: 'text', textAa: 'text-aa' };
for (const [name, a] of Object.entries(accents)) {
  for (const [key, label] of Object.entries(accentParts)) {
    // Sky has only wash and muted on the site, so its ink and text are extensions.
    // text-aa is always an extension: it is added by this system.
    const isExt = key === 'textAa' || (a.ext && (key === 'ink' || key === 'text'));
    const t = key === 'textAa' ? { ext: textAaNote } : isExt ? { ext: a.ext } : { from: a.from };
    // A value can also be an extension in the dark theme only (extDark), as with orange.
    const tDark = a.extDark?.[key] ? { ext: a.extDark[key] } : t;
    light.push(line(`accent-${name}-${label}`, a[key][0], t));
    dark.push(line(`accent-${name}-${label}`, a[key][1], tDark));
  }
}

// With no data-accent set, the accent roles are neutral. There is no default accent.
// Written inside each theme block so a nested theme resolves them correctly.
for (const label of Object.values(accentParts)) {
  light.push(line(`accent-${label}`, neutralAccent[label], { ext: neutralNote }));
  dark.push(line(`accent-${label}`, neutralAccent[label], { ext: neutralNote }));
}

const fixedLines = [];
const mobileLines = [];
for (const [name, t] of Object.entries(fixed)) {
  if (String(t.value).includes('var(')) {
    // Refers to a theme colour, so it must be declared inside each theme block.
    light.push(line(name, t.value, t));
    dark.push(line(name, t.value, t));
    continue;
  }
  fixedLines.push(line(name, t.value, t));
  if (t.mobile) mobileLines.push(line(name, t.mobile, t));
}
for (const [name, r] of Object.entries(roles)) {
  const p = `type-${name}`;
  fixedLines.push(line(`${p}-size`, r.size, r));
  fixedLines.push(`  --${p}-weight: ${r.weight};`);
  fixedLines.push(`  --${p}-stretch: ${r.stretch};`);
  fixedLines.push(`  --${p}-lh: ${r.lh};`);
  fixedLines.push(`  --${p}-tracking: ${r.tracking};`);
  if (r.mobile && r.mobile !== r.size) mobileLines.push(line(`${p}-size`, r.mobile, r));
}

const accentSelectors = Object.keys(accents)
  .map(
    (n) =>
      `[data-accent="${n}"] {\n  --accent-wash: var(--accent-${n}-wash);\n  --accent-muted: var(--accent-${n}-muted);\n  --accent-ink: var(--accent-${n}-ink);\n  --accent-text: var(--accent-${n}-text);\n  --accent-text-aa: var(--accent-${n}-text-aa);\n}`,
  )
  .join('\n');

const css = `/* GENERATED by tokens/build.mjs from tokens.mjs. Do not edit by hand.
 *
 * Every value has a comment beside it:
 *   site: ...       read from the live portfolio CSS
 *   EXTENSION: ...  the portfolio has no answer, so the value is proposed
 *
 * Themes: light is the default. Dark follows the system, and data-theme="light" or
 * data-theme="dark" on any element forces a theme for everything inside it.
 * Accent: neutral by default. A product picks one of orange, violet, amber, teal or sky and sets
 * data-accent on its screen. One per screen, never mixed. There is no brand accent.
 */

:root,
[data-theme="light"] {
  color-scheme: light;
${light.join('\n')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${dark.map((l) => '  ' + l).join('\n')}
  }
}

[data-theme="dark"] {
  color-scheme: dark;
${dark.join('\n')}
}

:root {
${fixedLines.join('\n')}
}

@media (max-width: ${breakpoints.mobile.max}px) {
  :root {
${mobileLines.map((l) => '  ' + l).join('\n')}
  }
}

/* Reduced motion: every duration collapses. The site honours this with its own toggle too. */
@media (prefers-reduced-motion: reduce) {
  :root {
    --dur-press: 0s; --dur-fast: 0s; --dur-base: 0s; --dur-slow: 0s; --dur-spring: 0s; --dur-colour: 0s;
  }
}

${accentSelectors}
`;

writeFileSync(out('tokens.css'), css);

// ---- EXTENSIONS.md ----------------------------------------------------------------------------
// Tokens that share the same reason are listed on one line.
const byWhy = new Map();
const add = (name, why) => byWhy.set(why, [...(byWhy.get(why) ?? []), name]);
for (const [name, t] of Object.entries({ ...themed, ...fixed })) if (t.ext) add(name, t.ext);
for (const [name, a] of Object.entries(accents)) if (a.ext) add(`accent-${name}-ink, accent-${name}-text`, a.ext);
for (const [name, a] of Object.entries(accents)) for (const [key, why] of Object.entries(a.extDark ?? {})) add(`accent-${name}-${key} (dark only)`, why);
add('accent-<name>-text-aa (all five accents)', textAaNote);
add('accent-wash, accent-muted, accent-ink, accent-text, accent-text-aa', neutralNote);
add('prefers-reduced-motion block', 'Zeroes every duration at token level. The site has a Reduce motion toggle, but no token level rule.');
const rows = [...byWhy].map(([why, names]) => [names.join(', '), why]);

const md = `# Extensions

Every token that is not read from the live portfolio. Each one fills a gap the portfolio never needed to answer. This list feeds the "where it breaks" section of the README.

${rows.map(([n, why]) => `- \`${n}\`: ${why}`).join('\n')}
`;
writeFileSync(out('EXTENSIONS.md'), md);
console.log(`tokens.css written (${light.length} light, ${dark.length} dark, ${fixedLines.length} fixed). ${rows.length} extensions.`);
